const firstNames = ['Aarav', 'Advait', 'Akash', 'Amara', 'Arjun', 'Dev', 'Diya', 'Ishaan', 'Kavya', 'Kiran', 'Meera', 'Nikhil', 'Riya', 'Samar', 'Tanvi', 'Ved', 'Yash', 'Zara', 'Aanya', 'Dhruv']
const lastNames = ['Patel', 'Menon', 'Kapoor', 'Desai', 'Bose', 'Malhotra', 'Reddy', 'Chopra', 'Sharma', 'Mukherjee']
const departmentTargets = Object.fromEntries(departments.map((department) => [department, 140]))
const departmentCounts = Object.fromEntries(departments.map((department) => [department, seedStudents.filter((student) => student.department === department).length]))
const generatedStudents = []

for (let index = 0; index < 690; index += 1) {
  const department = departments.find((name) => departmentCounts[name] < departmentTargets[name])
  const idNumber = 1011 + index
  const template = seedStudents.find((student) => student.department === department) || seedStudents[index % seedStudents.length]
  const variation = ((idNumber * 7) % 25) - 12
  const clamp = (value, min = 35, max = 99) => Math.max(min, Math.min(max, value))
  const academic = clamp(template.academic + variation)
  const attendance = clamp(template.attendance + ((idNumber * 11) % 23) - 11)
  const lms = clamp(template.lms + ((idNumber * 13) % 27) - 13)
  const skills = clamp(template.skills + ((idNumber * 17) % 25) - 12)
  const placementReadiness = clamp(template.placementReadiness + ((idNumber * 19) % 29) - 14)
  const successScore = Math.round(academic * 0.3 + attendance * 0.25 + lms * 0.15 + skills * 0.15 + placementReadiness * 0.1 + 65 * 0.05)
  const riskLevel = attendance < 60 || academic < 55 ? 'High Risk' : successScore < 68 ? 'Medium Risk' : 'Low Risk'
  const firstName = firstNames[index % firstNames.length]
  const lastName = lastNames[Math.floor(index / firstNames.length) % lastNames.length]
  const semesterNumber = ((idNumber % 8) + 1)

  generatedStudents.push({
    ...template,
    id: `STU-${idNumber}`,
    name: `${firstName} ${lastName}`,
    email: `student${idNumber}@pulse.edu`,
    department,
    year: `${Math.ceil(semesterNumber / 2)}${['st', 'nd', 'rd', 'th'][Math.min(Math.ceil(semesterNumber / 2) - 1, 3)]} Year`,
    password: `PulseStu-${idNumber}!`,
    successScore,
    academic,
    attendance,
    lms,
    placement: placementReadiness,
    placementReadiness,
    skills,
    riskLevel,
    riskScore: 100 - successScore,
    cgpa: Number((Math.max(4, Math.min(10, academic / 10 + ((idNumber % 5) - 2) * 0.1))).toFixed(1)),
    semester: `Semester ${semesterNumber}`,
    attendanceTrend: template.attendanceTrend.map((value, trendIndex) => clamp(value + ((idNumber + trendIndex * 3) % 13) - 6)),
    academicTrend: template.academicTrend.map((value, trendIndex) => Number(Math.max(4, Math.min(10, value + (variation / 100) + ((trendIndex - 2) * 0.04))).toFixed(1))),
    subjects: template.subjects.map((subject, subjectIndex) => ({ ...subject, marks: clamp(subject.marks + ((idNumber + subjectIndex * 5) % 19) - 9) })),
    skillsMatrix: template.skillsMatrix.map((skill, skillIndex) => ({ ...skill, score: clamp(skill.score + ((idNumber + skillIndex * 7) % 21) - 10) })),
    lmsActivity: { ...template.lmsActivity, coursesCompleted: (idNumber % 8) + 2, videosWatched: 15 + (idNumber % 36), assignmentsSubmitted: 5 + (idNumber % 10), quizAttempts: 6 + (idNumber % 12), loginFrequency: 3 + (idNumber % 8), learningHours: 8 + (idNumber % 24) },
    attendanceBreakdown: { present: attendance, absent: 100 - attendance },
    assignments: { completed: 6 + (idNumber % 10), pending: idNumber % 5 },
  })
  departmentCounts[department] += 1
}

